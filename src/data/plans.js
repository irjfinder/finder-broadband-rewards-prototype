/**
 * Effective monthly price after applying the Finder reward, amortised over 12 months.
 *   effectivePrice = (promoPrice ?? standardPrice) - (finderReward / 12)
 */
export function getEffectivePrice(plan) {
  const base = plan.promoPrice ?? plan.standardPrice;
  const monthlyRewardValue = (plan.finderReward || 0) / 12;
  return base - monthlyRewardValue;
}

export function formatPrice(value, { decimals = 2 } = {}) {
  if (value == null) return '—';
  const fixed = value.toFixed(decimals);
  return `$${fixed.replace(/\.00$/, '')}`;
}

